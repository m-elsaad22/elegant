def unique_title(service_key: str, city: str, orig: str, r: Rng, post_id: int) -> str:
    svc = SERVICES[service_key]
    angle = _TITLE_ANGLES[post_id % len(_TITLE_ANGLES)]
    if "أفضل" in orig:
        return f"{svc['name']} في {city}: {angle}"
    forms = [
        f"{svc['kw_base']} في {city} — {angle}",
        f"{svc['name']} في {city} | {angle}",
        f"{svc['kw_base']} داخل {city}: {angle}",
        f"{city}: {svc['name']} — {angle}",
        f"{svc['kw_base']} {city} ({angle})",
    ]
    return forms[post_id % len(forms)]


def build_keyword(service_key: str, city: str, orig: str) -> str:
    off = {"finish", "landscape", "leak", "insulate", "drain"}
    if service_key in off:
        return f"{SERVICES[service_key]['kw_base']} في {city}"
    t = re.sub(r"\s+", " ", orig).strip()
    t = re.sub(r"\|.*", "", t).strip()
    t = re.sub(r"أفضل\s+", "", t)
    if 8 <= len(t) <= 70 and re.search(r"مسبح|مسابح|حمام|حوض|أحواض|تكلفة|أسعار", t):
        return t
    return f"{SERVICES[service_key]['kw_base']} في {city}"


def word_count(html_text: str) -> int:
    t = re.sub(r"<[^>]+>", " ", html_text)
    t = html.unescape(t)
    parts = re.findall(r"\S+", t)
    return len(parts)


