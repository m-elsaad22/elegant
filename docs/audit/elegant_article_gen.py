def related_links(ctx: dict, r: Rng, catalog: List[dict]) -> str:
    city = ctx["city"]
    sid = ctx["service_key"]
    same_city = [x for x in catalog if x.get("city") == city and x.get("service") != sid]
    same_svc = [x for x in catalog if x.get("service") == sid and x.get("city") != city]
    picks = r.sample(same_city, min(3, len(same_city))) + r.sample(same_svc, min(2, len(same_svc)))
    if not picks:
        return ""
    lis = []
    for it in picks[:4]:
        lis.append(f'<a href="{it["link"]}">{html.escape(it["title"])}</a>')
    return h2("مواضيع مرتبطة داخل الموقع", "links") + p("روابط لصفحات خدمة أخرى في نفس المدينة أو لنفس نوع العمل في مدينة ثانية.") + ul(lis)


