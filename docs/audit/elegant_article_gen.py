def extra_paragraphs(ctx: dict, r: Rng, n: int) -> str:
    out = []
    used = set()
    for i in range(n):
        lead, mid, tail = r.choice(_LEAD), r.choice(_MID), r.choice(_TAIL)
        fact = r.choice(_FACTS)
        key = (lead, mid, tail, fact)
        if key in used:
            fact = r.choice(_FACTS)
        used.add(key)
        sent = f"{lead}، {mid}. {fact} {tail}"
        out.append(p(fill(sent, ctx)))
    return "".join(out)


