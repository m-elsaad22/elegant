class Rng:
    def __init__(self, seed: str):
        h = hashlib.sha256(seed.encode("utf-8")).hexdigest()
        self.rnd = random.Random(int(h[:16], 16))

    def choice(self, seq):
        return self.rnd.choice(list(seq))

    def sample(self, seq, k):
        seq = list(seq)
        k = min(k, len(seq))
        return self.rnd.sample(seq, k)

    def shuffle(self, seq):
        x = list(seq)
        self.rnd.shuffle(x)
        return x

    def randint(self, a, b):
        return self.rnd.randint(a, b)

    def pick(self, seq, i_salt=0):
        seq = list(seq)
        return seq[(self.rnd.randint(0, 10_000) + i_salt) % len(seq)]


def fill(s: str, ctx: dict) -> str:
    for k, v in ctx.items():
        if isinstance(v, str):
            s = s.replace("{" + k + "}", v)
    return s


def p(*parts: str) -> str:
    return "<p>" + " ".join(x.strip() for x in parts if x) + "</p>"


def h2(text: str, hid: str) -> str:
    return f'<h2 id="{hid}">{text}</h2>'


def h3(text: str) -> str:
    return f"<h3>{text}</h3>"


def ul(items: Sequence[str]) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def ol(items: Sequence[str]) -> str:
    return "<ol>" + "".join(f"<li>{i}</li>" for i in items) + "</ol>"


def table(headers: List[str], rows: List[List[str]]) -> str:
    thead = "<thead><tr>" + "".join(f"<th>{h}</th>" for h in headers) + "</tr></thead>"
    body = "<tbody>" + "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows) + "</tbody>"
    return f'<div class="responsive-table"><table>{thead}{body}</table></div>'


def cards(items: List[Tuple[str, str, str]]) -> str:
    bits = []
    for icon, title, text in items:
        bits.append(f'<div class="feature-card"><i class="{icon}"></i><h3>{title}</h3><p>{text}</p></div>')
    return '<div class="features-grid">' + "".join(bits) + "</div>"


def steps(items: List[Tuple[str, str]]) -> str:
    bits = []
    for i, (title, text) in enumerate(items, 1):
        bits.append(f'<div class="step-card"><span class="step-number">{i:02d}</span><h3>{title}</h3><p>{text}</p></div>')
    return '<div class="steps-grid">' + "".join(bits) + "</div>"


